def label(text, name=None, wrap=False):
    widget = QLabel(text)
    if name:
        widget.setObjectName(name)
    widget.setWordWrap(wrap)
    return widget


def button(text, callback=None, name=None):
    widget = KineticButton(text)
    widget.setCursor(Qt.CursorShape.PointingHandCursor)
    if name:
        widget.setObjectName(name)
    if callback:
        widget.clicked.connect(callback)
    return widget


def card():
    frame = MaximalPanel()
    frame.setObjectName('card')
    layout = QVBoxLayout(frame)
    layout.setContentsMargins(24, 24, 24, 24)
    layout.setSpacing(16)
    return frame, layout


def nav_icon(index):
    paths = [
        '<rect x="3" y="3" width="18" height="18" rx="3"/><path d="M8 3v18M8 9h13"/>',
        '<circle cx="12" cy="12" r="9"/><path d="M12 7v5l4 2"/>',
        '<rect x="5" y="5" width="14" height="14" rx="3"/><path d="M9 1v4m6-4v4M9 19v4m6-4v4M1 9h4m-4 6h4m14-6h4m-4 6h4"/>',
        '<path d="M4 6h16M4 12h16M4 18h16"/><circle cx="9" cy="6" r="2" fill="CANVAS"/><circle cx="15" cy="12" r="2" fill="CANVAS"/><circle cx="9" cy="18" r="2" fill="CANVAS"/>',
    ]
    svg = f'<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24"><g fill="none" stroke="{COLORS['muted']}" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round">{paths[index]}</g></svg>'
    svg = svg.replace('CANVAS', COLORS['canvas'])
    pixmap = QPixmap(48, 48)
    pixmap.fill(Qt.GlobalColor.transparent)
    painter = QPainter(pixmap)
    QSvgRenderer(QByteArray(svg.encode())).render(painter)
    painter.end()
    return QIcon(pixmap)


def page(title, description):
    widget = QWidget()
    layout = QVBoxLayout(widget)
    layout.setContentsMargins(0, 0, 0, 0)
    layout.setSpacing(16)
    layout.addWidget(label(title, 'title'))
    layout.addWidget(label(description, 'muted', True))
    return widget, layout


